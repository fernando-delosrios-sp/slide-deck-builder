#!/usr/bin/env python3
"""
PowerPoint (.pptx) Exporter for Slide Deck Builder.

Exports Reveal.js HTML presentations into high-fidelity 16:9 widescreen
PowerPoint presentations built from scratch (without template layout pollution),
preserving exact CSS grid layouts, gradients, vector SVGs, and presenter notes.
"""

import os
import re
import sys
import yaml
import shutil
import tempfile
import subprocess
from pptx import Presentation
from pptx.util import Inches

def find_chrome():
    candidates = [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
        "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
        "/usr/bin/google-chrome",
        "/usr/bin/chromium",
        "/usr/bin/chromium-browser"
    ]
    for c in candidates:
        if os.path.exists(c) and os.access(c, os.X_OK):
            return c
    return None

def export_to_pptx(input_path, output_path=None):
    """
    Exports a presentation to a 16:9 widescreen PowerPoint deck (.pptx)
    compiled from Reveal.js slides from scratch.
    Accepts either a spec.yaml or a compiled deck.html.
    """
    input_path = os.path.abspath(input_path)
    spec_data = None
    spec_dir = None

    if input_path.endswith(".yaml") or input_path.endswith(".yml"):
        spec_path = input_path
        spec_dir = os.path.dirname(spec_path)
        html_path = os.path.join(spec_dir, "deck.html")
        if not output_path:
            output_path = os.path.join(spec_dir, "deck.pptx")
        try:
            with open(spec_path, "r", encoding="utf-8") as f:
                spec_data = yaml.safe_load(f)
        except Exception as e:
            print(f"Warning: Could not read spec for presenter notes: {e}")
    else:
        html_path = input_path
        spec_dir = os.path.dirname(html_path)
        potential_spec = os.path.join(spec_dir, "spec.yaml")
        if os.path.exists(potential_spec):
            try:
                with open(potential_spec, "r", encoding="utf-8") as f:
                    spec_data = yaml.safe_load(f)
            except Exception:
                pass
        if not output_path:
            output_path = os.path.splitext(html_path)[0] + ".pptx"

    if not os.path.exists(html_path):
        if spec_dir and os.path.exists(os.path.join(spec_dir, "spec.yaml")):
            print(f"deck.html not found at {html_path}. Compiling from spec...")
            builder_py = os.path.join(os.path.dirname(__file__), "builder.py")
            subprocess.run([sys.executable, builder_py, os.path.join(spec_dir, "spec.yaml"), html_path], check=True)
        else:
            print(f"Error: HTML presentation not found: {html_path}")
            sys.exit(1)

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    file_url = f"file://{html_path}"
    print(f"Exporting PowerPoint deck from {html_path}...")

    # Extract notes from spec if available
    slides_notes = []
    if spec_data and isinstance(spec_data.get("slides"), list):
        for s in spec_data["slides"]:
            slides_notes.append(s.get("notes", "") or "")

    chrome_path = find_chrome()
    with tempfile.TemporaryDirectory() as tmp_dir:
        tmp_pdf = os.path.join(tmp_dir, "slide.pdf")
        cmd = [
            "npx", "--yes", "decktape", "reveal",
            "-s", "1920x1080",
            "--screenshots",
            "--screenshots-directory", tmp_dir,
            "--screenshots-format", "png",
            "--load-pause", "1000",
            "--pause", "500",
            file_url,
            tmp_pdf
        ]
        if chrome_path:
            cmd.extend(["--chrome-path", chrome_path])

        result = subprocess.run(cmd)
        if result.returncode != 0:
            print("Error: decktape failed to capture presentation slides.")
            sys.exit(result.returncode)

        # Collect captured screenshots
        screenshot_files = []
        pattern = re.compile(r"slide_(\d+)_\d+x\d+\.png")
        for fname in os.listdir(tmp_dir):
            match = pattern.match(fname)
            if match:
                index = int(match.group(1))
                screenshot_files.append((index, os.path.join(tmp_dir, fname)))

        screenshot_files.sort(key=lambda x: x[0])

        if not screenshot_files:
            print("Error: No slide screenshots were generated by decktape.")
            sys.exit(1)

        print(f"Assembling {len(screenshot_files)} slides into PowerPoint presentation...")

        # Build clean PPTX from scratch
        prs = Presentation()
        prs.slide_width = Inches(13.333333)  # 16:9 standard widescreen
        prs.slide_height = Inches(7.5)
        blank_layout = prs.slide_layouts[6]

        for idx, (slide_num, img_path) in enumerate(screenshot_files):
            slide = prs.slides.add_slide(blank_layout)
            slide.shapes.add_picture(
                img_path,
                Inches(0),
                Inches(0),
                width=prs.slide_width,
                height=prs.slide_height
            )

            # Attach speaker notes if available
            note_text = ""
            if idx < len(slides_notes):
                note_text = slides_notes[idx]
            if note_text:
                notes_slide = slide.notes_slide
                tf = notes_slide.notes_text_frame
                tf.text = note_text

        prs.save(output_path)

    if os.path.exists(output_path) and os.path.getsize(output_path) > 0:
        file_size_mb = os.path.getsize(output_path) / (1024 * 1024)
        print(f"\nPowerPoint deck successfully generated: {output_path} ({len(screenshot_files)} slides, {file_size_mb:.1f} MB)")
        return output_path
    else:
        print(f"\nError: Failed to generate PowerPoint output at {output_path}")
        sys.exit(1)

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python export_pptx.py <spec_file.yaml | deck.html> [output_deck.pptx]")
        sys.exit(1)
    in_arg = sys.argv[1]
    out_arg = sys.argv[2] if len(sys.argv) > 2 else None
    export_to_pptx(in_arg, out_arg)
